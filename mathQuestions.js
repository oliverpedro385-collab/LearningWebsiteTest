/* ========================================
   CURRENT QUESTION
   ======================================== */

let currentQuestion;


/* ========================================
   SHUFFLE
   ======================================== */

function shuffleArray(array) {

    const shuffled =
        [...array];


    for (
        let i =
            shuffled.length - 1;

        i > 0;

        i--
    ) {

        const j =
            Math.floor(
                Math.random()
                * (i + 1)
            );


        [
            shuffled[i],
            shuffled[j]
        ] = [
            shuffled[j],
            shuffled[i]
        ];
    }


    return shuffled;
}


/* ========================================
   LOAD QUESTION
   ======================================== */

function loadQuestion() {

    const questions =
        gradeQuestionSets[
            selectedGrade
        ];


    const randomIndex =
        Math.floor(
            Math.random()
            * questions.length
        );


    const questionData =
        questions[randomIndex];


    const language =
        getLanguage();


    currentQuestion =
        questionData[language]
        || questionData["en"];


    document.getElementById(
        "question"
    ).textContent =
        currentQuestion.question;


    const answersContainer =
        document.getElementById(
            "answers"
        );


    answersContainer.innerHTML =
        "";


    const shuffledAnswers =
        shuffleArray(
            currentQuestion.answers
        );


    shuffledAnswers.forEach(
        function(answer) {

            const button =
                document.createElement(
                    "button"
                );


            button.textContent =
                answer;


            button.classList.add(
                "answerButton"
            );


            button.onclick =
                function() {

                    checkAnswer(
                        answer,
                        button
                    );
                };


            answersContainer.appendChild(
                button
            );
        }
    );


    document.getElementById(
        "result"
    ).textContent =
        "";


    document.getElementById(
        "nextButton"
    ).style.display =
        "none";
}


/* ========================================
   CHECK ANSWER
   ======================================== */

function checkAnswer(
    answer,
    clickedButton
) {

    const result =
        document.getElementById(
            "result"
        );


    const answerButtons =
        document.querySelectorAll(
            ".answerButton"
        );


    answerButtons.forEach(
        function(button) {

            button.disabled =
                true;
        }
    );


    if (
        answer ===
        currentQuestion.correctAnswer
    ) {

        result.textContent =
            t("correct");


        result.style.color =
            "green";


        clickedButton.style.backgroundColor =
            "lightgreen";

    } else {

        result.textContent =
            t("wrong");


        result.style.color =
            "red";


        clickedButton.style.backgroundColor =
            "lightcoral";


        answerButtons.forEach(
            function(button) {

                if (
                    button.textContent ===
                    currentQuestion.correctAnswer
                ) {

                    button.style.backgroundColor =
                        "lightgreen";
                }
            }
        );
    }


    document.getElementById(
        "nextButton"
    ).style.display =
        "inline-block";
}


/* ========================================
   START
   ======================================== */

loadQuestion();