let currentQuestion = null;

let currentQuestionData = null;

let questionsAnswered = 0;

let correctAnswers = 0;

const totalQuestions = 10;

const mistakesByTopic = {};


/* ========================================
   SHUFFLE
   ======================================== */

function shuffleArray(array) {

    const shuffled =
        [...array];


    for (
        let i =
            shuffled.length - 1;

        i > 0;

        i--
    ) {

        const j =
            Math.floor(
                Math.random()
                * (i + 1)
            );


        [
            shuffled[i],
            shuffled[j]
        ] = [
            shuffled[j],
            shuffled[i]
        ];
    }


    return shuffled;
}


/* ========================================
   PROGRESS
   ======================================== */

function updateQuizProgress() {

    const progressText =
        document.getElementById(
            "progressText"
        );

    const progressFill =
        document.getElementById(
            "quizProgressFill"
        );


    if (!progressText || !progressFill) {
        return;
    }


    const language =
        getLanguage();


    if (
        language === "pt-BR"
    ) {

        progressText.textContent =
            "Questão "
            + Math.min(
                questionsAnswered + 1,
                totalQuestions
            )
            + " de "
            + totalQuestions;

    } else {

        progressText.textContent =
            "Question "
            + Math.min(
                questionsAnswered + 1,
                totalQuestions
            )
            + " of "
            + totalQuestions;
    }


    const progress =
        (
            questionsAnswered /
            totalQuestions
        ) * 100;


    progressFill.style.width =
        progress + "%";
}


/* ========================================
   GRADE LABEL
   ======================================== */

function updateGradeLabel() {

    document.getElementById(
        "gradeLabel"
    ).textContent =
        t("midDay")
        + " • "
        + t("grade" + selectedGrade);
}


/* ========================================
   LOAD QUESTION
   ======================================== */

function loadQuestion() {

    const questions =
        gradeQuestionSets[
            selectedGrade
        ];


    const randomIndex =
        Math.floor(
            Math.random()
            * questions.length
        );


    currentQuestionData =
        questions[randomIndex];


    const language =
        getLanguage();


    currentQuestion =
        currentQuestionData[language]
        || currentQuestionData["en"];


    renderQuestion();

    updateGradeLabel();

    updateQuizProgress();
}


/* ========================================
   RENDER QUESTION
   ======================================== */

function renderQuestion() {

    document.getElementById(
        "question"
    ).textContent =
        currentQuestion.question;


    const answersContainer =
        document.getElementById(
            "answers"
        );


    answersContainer.innerHTML =
        "";


    const shuffledAnswers =
        shuffleArray(
            currentQuestion.answers
        );


    shuffledAnswers.forEach(
        function(answer) {

            const button =
                document.createElement(
                    "button"
                );


            button.textContent =
                answer;


            button.classList.add(
                "answerButton"
            );


            button.onclick =
                function() {

                    checkAnswer(
                        answer,
                        button
                    );
                };


            answersContainer.appendChild(
                button
            );
        }
    );


    document.getElementById(
        "result"
    ).textContent =
        "";


    document.getElementById(
        "nextButton"
    ).style.display =
        "none";
}


/* ========================================
   CHECK ANSWER
   ======================================== */

function checkAnswer(
    answer,
    clickedButton
) {

    const result =
        document.getElementById(
            "result"
        );


    const answerButtons =
        document.querySelectorAll(
            ".answerButton"
        );


    answerButtons.forEach(
        function(button) {

            button.disabled =
                true;
        }
    );


    const language =
        getLanguage();


    const topic =
        currentQuestionData.topic[language]
        || currentQuestionData.topic.en;


    if (
        answer ===
        currentQuestion.correctAnswer
    ) {

        correctAnswers++;


        result.textContent =
            t("correct");


        result.style.color =
            "green";


        clickedButton.style.backgroundColor =
            "lightgreen";

    } else {

        result.textContent =
            t("wrong");


        result.style.color =
            "red";


        clickedButton.style.backgroundColor =
            "lightcoral";


        if (
            !mistakesByTopic[topic]
        ) {

            mistakesByTopic[topic] =
                0;
        }


        mistakesByTopic[topic]++;


        answerButtons.forEach(
            function(button) {

                if (
                    button.textContent ===
                    currentQuestion.correctAnswer
                ) {

                    button.style.backgroundColor =
                        "lightgreen";
                }
            }
        );
    }


    questionsAnswered++;


    updateQuizProgress();


    if (
        questionsAnswered >=
        totalQuestions
    ) {

        setTimeout(
            finishQuiz,
            700
        );

        return;
    }


    document.getElementById(
        "nextButton"
    ).style.display =
        "inline-block";
}


