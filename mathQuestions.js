/* =========================================================
   FORMAT SCORE
   ========================================================= */

function formatScore(score) {
    if (
        Number.isInteger(score)
    ) {
        return String(score);
    }

    return score.toFixed(1);
}


/* =========================================================
   HINT RESET
   ========================================================= */

function resetHint() {
    if (hintTalkTimer) {
        clearTimeout(
            hintTalkTimer
        );

        hintTalkTimer = null;
    }

    hintText.textContent =
        getCurrentLanguage() === "pt-BR"
            ? "Estou aqui para ajudar!"
            : "I'm here to help!";

    hintText.classList.remove(
        "shown"
    );

    hintButton.textContent =
        getCurrentLanguage() === "pt-BR"
            ? "Mostrar Dica"
            : "Show Hint";

    assistantFace.textContent =
        ":)";

    assistantFace.classList.remove(
        "talking"
    );
}


/* =========================================================
   SHOW / HIDE HINT
   ========================================================= */

function showHint() {
    if (!currentQuestion) {
        return;
    }

    if (
        hintText.classList.contains(
            "shown"
        )
    ) {
        hintText.textContent =
            getCurrentLanguage() === "pt-BR"
                ? "Estou aqui para ajudar!"
                : "I'm here to help!";

        hintText.classList.remove(
            "shown"
        );

        hintButton.textContent =
            getCurrentLanguage() === "pt-BR"
                ? "Mostrar Dica"
                : "Show Hint";

        assistantFace.textContent =
            ":)";

        assistantFace.classList.remove(
            "talking"
        );

        if (hintTalkTimer) {
            clearTimeout(
                hintTalkTimer
            );

            hintTalkTimer = null;
        }

        return;
    }


    if (
        !hintUsedThisQuestion
    ) {
        hintUsedThisQuestion =
            true;

        totalHintsUsed++;
    }


    const language =
        getCurrentLanguage();


    hintText.textContent =
        currentQuestion[
            language
        ].hint;

    hintText.classList.add(
        "shown"
    );

    hintButton.textContent =
        language === "pt-BR"
            ? "Esconder Dica"
            : "Hide Hint";


    assistantFace.textContent =
        ":D";

    assistantFace.classList.add(
        "talking"
    );


    if (hintTalkTimer) {
        clearTimeout(
            hintTalkTimer
        );
    }


    hintTalkTimer =
        setTimeout(
            () => {
                assistantFace.textContent =
                    ":)";

                assistantFace.classList.remove(
                    "talking"
                );

                hintTalkTimer = null;
            },
            2500
        );
}


