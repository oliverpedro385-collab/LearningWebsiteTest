// ==================================================
// SHOW / HIDE HINT
// ==================================================

function showHint() {

    if (!currentQuestion) {
        return;
    }


    // ----------------------------------------------
    // HIDE THE HINT
    // ----------------------------------------------

    if (
        hintText.classList.contains(
            "shown"
        )
    ) {

        hintText.textContent =
            "Estou aqui para ajudar!";

        hintText.classList.remove(
            "shown"
        );

        hintButton.textContent =
            "Mostrar Dica";

        assistantFace.textContent =
            ":)";

        assistantFace.classList.remove(
            "talking"
        );

        if (hintTalkTimer) {

            clearTimeout(
                hintTalkTimer
            );

            hintTalkTimer = null;
        }

        return;
    }


    // ----------------------------------------------
    // COUNT THE HINT ONLY ONCE
    // ----------------------------------------------

    if (!hintUsedThisQuestion) {

        hintUsedThisQuestion = true;

        totalHintsUsed++;
    }


    // ----------------------------------------------
    // SHOW THE HINT
    // ----------------------------------------------

    hintText.textContent =
        currentQuestion.hint;

    hintText.classList.add(
        "shown"
    );

    hintButton.textContent =
        "Esconder Dica";


    // ----------------------------------------------
    // MAKE THE ASSISTANT TALK
    // ----------------------------------------------

    assistantFace.textContent =
        ":D";

    assistantFace.classList.add(
        "talking"
    );


    // ----------------------------------------------
    // RETURN TO NORMAL FACE
    // ----------------------------------------------

    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );
    }

    hintTalkTimer =
        setTimeout(
            () => {

                assistantFace.textContent =
                    ":)";

                assistantFace.classList.remove(
                    "talking"
                );

                hintTalkTimer = null;

            },
            2500
        );
}


// ==================================================
// RENDER ANSWERS
// ==================================================

function renderAnswers() {

    answersElement.innerHTML =
        "";

    const questionData =
        currentQuestion;

    shuffle(
        questionData.answers
    ).forEach(
        answer => {

            const button =
                document.createElement(
                    "button"
                );

            button.type =
                "button";

            button.className =
                "answerButton";

            button.textContent =
                answer;

            button.addEventListener(
                "click",
                () => {
                    checkAnswer(
                        answer,
                        button
                    );
                }
            );

            answersElement.appendChild(
                button
            );
        }
    );
}


// ==================================================
// LOAD QUESTION
// ==================================================

function loadQuestion() {

    answeredThisQuestion =
        false;

    hintUsedThisQuestion =
        false;

    resetHint();

    resultElement.textContent =
        "";

    resultElement.className =
        "quizResult";

    nextButton.style.display =
        "none";


    const pool =
        historyQuestions[
            currentGrade
        ];


    if (
        questionOrder.length > 0
    ) {

        currentQuestion =
            pool[
                questionOrder[
                    questionOrderIndex
                ]
            ];

        questionOrderIndex++;

    } else {

        currentQuestion =
            pool[
                Math.floor(
                    Math.random() *
                    pool.length
                )
            ];
    }


    const topic =
        currentQuestion.topic;

    if (
        mistakesByTopic[topic]
        === undefined
    ) {
        mistakesByTopic[topic] =
            0;
    }


    gradeLabel.textContent =
        `História • Ano ${currentGrade}`;

    questionElement.textContent =
        currentQuestion.question;


    renderAnswers();

    updateProgress();
}


// ==================================================
// CHECK ANSWER
// ==================================================

function checkAnswer(
    selectedAnswer,
    clickedButton
) {

    if (
        answeredThisQuestion
    ) {
        return;
    }

    answeredThisQuestion =
        true;


    const answerButtons =
        answersElement.querySelectorAll(
            ".answerButton"
        );


    answerButtons.forEach(
        button => {
            button.disabled =
                true;
        }
    );


    const isCorrect =
        selectedAnswer ===
        currentQuestion.correctAnswer;


    // ----------------------------------------------
    // CORRECT
    // ----------------------------------------------

    if (isCorrect) {

        correctAnswers++;


        if (
            hintUsedThisQuestion
        ) {

            hintPenaltyPoints +=
                0.5;
        }


        clickedButton.classList.add(
            "correct"
        );

        resultElement.textContent =
            "Correto!";

        resultElement.className =
            "quizResult correctResult";
    }


    // ----------------------------------------------
    // WRONG
    // ----------------------------------------------

    else {

        clickedButton.classList.add(
            "wrong"
        );


        answerButtons.forEach(
            button => {

                if (
                    button.textContent ===
                    currentQuestion.correctAnswer
                ) {

                    button.classList.add(
                        "correct"
                    );
                }
            }
        );


        mistakesByTopic[
            currentQuestion.topic
        ] =
            (
                mistakesByTopic[
                    currentQuestion.topic
                ] || 0
            ) + 1;


        resultElement.textContent =
            "Errado!";

        resultElement.className =
            "quizResult wrongResult";
    }


    // ----------------------------------------------
    // STOP THE ASSISTANT TALKING
    // ----------------------------------------------

    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );

        hintTalkTimer = null;
    }

    assistantFace.textContent =
        ":)";

    assistantFace.classList.remove(
        "talking"
    );


    // ----------------------------------------------
    // NEXT BUTTON
    // ----------------------------------------------

    nextButton.textContent =
        questionsAnswered + 1 >=
        totalQuestions
            ? "Ver Resultado"
            : "Próxima Questão";

    nextButton.style.display =
        "block";
}


// ==================================================
// NEXT QUESTION
// ==================================================

nextButton.addEventListener(
    "click",
    () => {

        if (
            !answeredThisQuestion
        ) {
            return;
        }


        questionsAnswered++;


        if (
            questionsAnswered >=
            totalQuestions
        ) {

            finishQuiz();

            return;
        }


        loadQuestion();
    }
);


// ==================================================
// FINISH QUIZ
// ==================================================

function finishQuiz() {

    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );

        hintTalkTimer = null;
    }


    const finalScore =
        Math.max(
            0,
            correctAnswers -
            hintPenaltyPoints
        );


    const percentage =
        Math.round(
            (
                finalScore /
                totalQuestions
            ) * 100
        );


    let weakestTopic =
        "";

    let highestMistakes =
        0;


    Object.keys(
        mistakesByTopic
    ).forEach(
        topic => {

            if (
                mistakesByTopic[
                    topic
                ] > highestMistakes
            ) {

                highestMistakes =
                    mistakesByTopic[
                        topic
                    ];

                weakestTopic =
                    topic;
            }
        }
    );


    let feedback;


    if (
        finalScore === 10
    ) {

        feedback =
            "Perfeito! Você mandou muito bem!";

    } else if (
        finalScore >= 8
    ) {

        feedback =
            "Muito bom! Você está aprendendo bastante História.";

    } else if (
        finalScore >= 6
    ) {

        feedback =
            "Bom trabalho! Continue praticando para aprender ainda mais.";

    } else if (
        finalScore >= 4
    ) {

        feedback =
            "Você já tem uma boa base. Continue praticando!";

    } else {

        feedback =
            "Não tem problema! Revise os assuntos e tente novamente.";
    }


    quizContainer.innerHTML =
        "";


    const completeScreen =
        document.createElement(
            "div"
        );

    completeScreen.className =
        "quizComplete";


    const title =
        document.createElement(
            "h2"
        );

    title.textContent =
        "Quiz Completo!";

    completeScreen.appendChild(
        title
    );


    const scoreElement =
        document.createElement(
            "div"
        );

    scoreElement.className =
        "quizScore";

    scoreElement.textContent =
        `${formatScore(finalScore)}/${totalQuestions}`;

    completeScreen.appendChild(
        scoreElement
    );


    const percentageElement =
        document.createElement(
            "div"
        );

    percentageElement.className =
        "quizPercentage";

    percentageElement.textContent =
        `${percentage}%`;

    completeScreen.appendChild(
        percentageElement
    );


    const feedbackElement =
        document.createElement(
            "p"
        );

    feedbackElement.className =
        "quizFeedback";

    feedbackElement.textContent =
        feedback;

    completeScreen.appendChild(
        feedbackElement
    );


    if (
        weakestTopic
    ) {

        const weakTopicElement =
            document.createElement(
                "p"
            );

        weakTopicElement.className =
            "quizWeakTopic";

        weakTopicElement.textContent =
            `Você teve mais dificuldade em: ${weakestTopic}`;

        completeScreen.appendChild(
            weakTopicElement
        );
    }


    const statsElement =
        document.createElement(
            "p"
        );

    statsElement.className =
        "quizHintStats";

    statsElement.textContent =
        `Dicas usadas: ${totalHintsUsed}`;

    completeScreen.appendChild(
        statsElement
    );


    const restartButton =
        document.createElement(
            "button"
        );

    restartButton.type =
        "button";

    restartButton.className =
        "nextButton";

    restartButton.textContent =
        "Tentar Novamente";


    restartButton.addEventListener(
        "click",
        () => {

            window.location.reload();

        }
    );


    completeScreen.appendChild(
        restartButton
    );


    quizContainer.appendChild(
        completeScreen
    );


    if (
        finalScore === 10
    ) {

        createConfetti();
    }
}


// ==================================================
// CONFETTI
// ==================================================

function createConfetti() {

    const count =
        80;


    for (
        let i = 0;
        i < count;
        i++
    ) {

        const piece =
            document.createElement(
                "div"
            );


        piece.textContent =
            "•";


        piece.style.position =
            "fixed";

        piece.style.left =
            `${Math.random() * 100}%`;

        piece.style.top =
            "-20px";

        piece.style.fontSize =
            `${12 + Math.random() * 18}px`;

        piece.style.zIndex =
            "9999";

        piece.style.pointerEvents =
            "none";


        document.body.appendChild(
            piece
        );


        const duration =
            1500 +
            Math.random() * 1800;


        const horizontal =
            (
                Math.random() - 0.5
            ) * 250;


        const animation =
            piece.animate(
                [
                    {
                        transform:
                            "translate(0, 0) rotate(0deg)",
                        opacity: 1
                    },
                    {
                        transform:
                            `translate(${horizontal}px, 110vh) rotate(720deg)`,
                        opacity: 0
                    }
                ],
                {
                    duration:
                        duration,

                    easing:
                        "ease-out"
                }
            );


        animation.finished
            .then(
                () => {
                    piece.remove();
                }
            )
            .catch(
                () => {
                    piece.remove();
                }
            );
    }
}


