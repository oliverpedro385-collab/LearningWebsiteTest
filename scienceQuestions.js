// ==================================================
// GET GRADE
// ==================================================

function getGradeFromURL() {

    const params =
        new URLSearchParams(
            window.location.search
        );

    const grade =
        Number(
            params.get("grade")
        );

    if (
        grade >= 1 &&
        grade <= 5 &&
        scienceQuestions[grade]
    ) {
        return grade;
    }

    return 1;
}


// ==================================================
// SHUFFLE
// ==================================================

function shuffle(array) {

    const shuffled =
        [...array];

    for (
        let i = shuffled.length - 1;
        i > 0;
        i--
    ) {

        const j =
            Math.floor(
                Math.random() *
                (i + 1)
            );

        [
            shuffled[i],
            shuffled[j]
        ] = [
            shuffled[j],
            shuffled[i]
        ];
    }

    return shuffled;
}


// ==================================================
// FORMAT SCORE
// ==================================================

function formatScore(score) {

    if (
        Number.isInteger(score)
    ) {
        return String(score);
    }

    return score.toFixed(1);
}


