// ==================================================

function createConfetti() {

    const count =
        80;


    for (
        let i = 0;
        i < count;
        i++
    ) {

        const piece =
            document.createElement(
                "div"
            );


        piece.textContent =
            "•";


        piece.style.position =
            "fixed";

        piece.style.left =
            `${Math.random() * 100}%`;

        piece.style.top =
            "-20px";

        piece.style.fontSize =
            `${12 + Math.random() * 18}px`;

        piece.style.zIndex =
            "9999";

        piece.style.pointerEvents =
            "none";


        document.body.appendChild(
            piece
        );


        const duration =
            1500 +
            Math.random() * 1800;


        const horizontal =
            (
                Math.random() - 0.5
            ) * 250;


        const animation =
            piece.animate(
                [
                    {
                        transform:
                            "translate(0, 0) rotate(0deg)",
                        opacity: 1
                    },
                    {
                        transform:
                            `translate(${horizontal}px, 110vh) rotate(720deg)`,
                        opacity: 0
                    }
                ],
                {
                    duration:
                        duration,

                    easing:
                        "ease-out"
                }
            );


        animation.finished
            .then(
                () => {

                    piece.remove();

                }
            )
            .catch(
                () => {

                    piece.remove();

                }
            );
    }
}


