function finishQuiz() {

    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );

        hintTalkTimer = null;
    }


    const finalScore =
        Math.max(
            0,
            correctAnswers -
            hintPenaltyPoints
        );


    const percentage =
        Math.round(
            (
                finalScore /
                totalQuestions
            ) * 100
        );


    let weakestTopic =
        "";

    let highestMistakes =
        0;


    Object.keys(
        mistakesByTopic
    ).forEach(
        topic => {

            if (
                mistakesByTopic[
                    topic
                ] > highestMistakes
            ) {

                highestMistakes =
                    mistakesByTopic[
                        topic
                    ];

                weakestTopic =
                    topic;
            }
        }
    );


    let feedback;


    if (
        finalScore === 10
    ) {

        feedback =
            "Perfeito! Você mandou muito bem!";

    } else if (
        finalScore >= 8
    ) {

        feedback =
            "Muito bom! Você está aprendendo bastante Ciências.";

    } else if (
        finalScore >= 6
    ) {

        feedback =
            "Bom trabalho! Continue praticando para aprender ainda mais.";

    } else if (
        finalScore >= 4
    ) {

        feedback =
            "Você já tem uma boa base. Continue praticando!";

    } else {

        feedback =
            "Não tem problema! Revise os assuntos e tente novamente.";
    }


    quizContainer.innerHTML =
        "";


    const completeScreen =
        document.createElement(
            "div"
        );

    completeScreen.className =
        "quizComplete";


    const title =
        document.createElement(
            "h2"
        );

    title.textContent =
        "Quiz Completo!";

    completeScreen.appendChild(
        title
    );


    const scoreElement =
        document.createElement(
            "div"
        );

    scoreElement.className =
        "quizScore";

    scoreElement.textContent =
        `${formatScore(finalScore)}/${totalQuestions}`;

    completeScreen.appendChild(
        scoreElement
    );


    const percentageElement =
        document.createElement(
            "div"
        );

    percentageElement.className =
        "quizPercentage";

    percentageElement.textContent =
        `${percentage}%`;

    completeScreen.appendChild(
        percentageElement
    );


    const feedbackElement =
        document.createElement(
            "p"
        );

    feedbackElement.className =
        "quizFeedback";

    feedbackElement.textContent =
        feedback;

    completeScreen.appendChild(
        feedbackElement
    );


    if (
        weakestTopic
    ) {

        const weakTopicElement =
            document.createElement(
                "p"
            );

        weakTopicElement.className =
            "quizWeakTopic";

        weakTopicElement.textContent =
            `Você teve mais dificuldade em: ${weakestTopic}`;

        completeScreen.appendChild(
            weakTopicElement
        );
    }


    const statsElement =
        document.createElement(
            "p"
        );

    statsElement.className =
        "quizHintStats";

    statsElement.textContent =
        `Dicas usadas: ${totalHintsUsed}`;

    completeScreen.appendChild(
        statsElement
    );


    const restartButton =
        document.createElement(
            "button"
        );

    restartButton.type =
        "button";

    restartButton.className =
        "nextButton";

    restartButton.textContent =
        "Tentar Novamente";


    restartButton.addEventListener(
        "click",
        () => {

            window.location.reload();

        }
    );


    completeScreen.appendChild(
        restartButton
    );


    quizContainer.appendChild(
        completeScreen
    );


    if (
        finalScore === 10
    ) {

        createConfetti();
    }
}


