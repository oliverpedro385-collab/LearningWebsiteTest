// ==================================================
// RESET HINT
// ==================================================

function resetHint() {

    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );

        hintTalkTimer = null;
    }

    hintTitle.textContent =
        "Dica";

    hintText.textContent =
        "Estou aqui para ajudar!";

    hintText.classList.remove(
        "shown"
    );

    hintButton.textContent =
        "Mostrar Dica";

    assistantFace.textContent =
        ":)";

    assistantFace.classList.remove(
        "talking"
    );
}


// ==================================================
// SHOW / HIDE HINT
// ==================================================

function showHint() {

    if (!currentQuestion) {
        return;
    }


    if (
        hintText.classList.contains(
            "shown"
        )
    ) {

        hintText.textContent =
            "Estou aqui para ajudar!";

        hintText.classList.remove(
            "shown"
        );

        hintButton.textContent =
            "Mostrar Dica";

        assistantFace.textContent =
            ":)";

        assistantFace.classList.remove(
            "talking"
        );

        if (hintTalkTimer) {

            clearTimeout(
                hintTalkTimer
            );

            hintTalkTimer = null;
        }

        return;
    }


    if (!hintUsedThisQuestion) {

        hintUsedThisQuestion = true;

        totalHintsUsed++;
    }


    hintText.textContent =
        currentQuestion.hint;

    hintText.classList.add(
        "shown"
    );

    hintButton.textContent =
        "Esconder Dica";


    assistantFace.textContent =
        ":D";

    assistantFace.classList.add(
        "talking"
    );


    if (hintTalkTimer) {

        clearTimeout(
            hintTalkTimer
        );
    }


    hintTalkTimer =
        setTimeout(
            () => {

                assistantFace.textContent =
                    ":)";

                assistantFace.classList.remove(
                    "talking"
                );

                hintTalkTimer = null;

            },
            2500
        );
}


// ==================================================
// RENDER ANSWERS
// ==================================================

function renderAnswers() {

    answersElement.innerHTML =
        "";

    shuffle(
        currentQuestion.answers
    ).forEach(
        answer => {

            const button =
                document.createElement(
                    "button"
                );

            button.type =
                "button";

            button.className =
                "answerButton";

            button.textContent =
                answer;

            button.addEventListener(
                "click",
                () => {

                    checkAnswer(
                        answer,
                        button
                    );

                }
            );

            answersElement.appendChild(
                button
            );
        }
    );
}


// ==================================================
// LOAD QUESTION
// ==================================================

function loadQuestion() {

    answeredThisQuestion =
        false;

    hintUsedThisQuestion =
        false;

    resetHint();

    resultElement.textContent =
        "";

    resultElement.className =
        "quizResult";

    nextButton.style.display =
        "none";


    const pool =
        scienceQuestions[
            currentGrade
        ];


    currentQuestion =
        pool[
            questionOrder[
                questionOrderIndex
            ]
        ];

    questionOrderIndex++;


    if (
        mistakesByTopic[
            currentQuestion.topic
        ] === undefined
    ) {

        mistakesByTopic[
            currentQuestion.topic
        ] = 0;
    }


    gradeLabel.textContent =
        `Ciências • Ano ${currentGrade}`;

    questionElement.textContent =
        currentQuestion.question;


    renderAnswers();

    updateProgress();
}


